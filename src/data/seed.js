// Dates are generated relative to "now" so the dashboard always looks current.

const daysAgo = (n) => {
  const d = new Date()
  d.setDate(d.getDate() - n)
  d.setHours(9 + (n % 6), (n * 7) % 60, 0, 0)
  return d.toISOString()
}
const daysAhead = (n) => {
  const d = new Date()
  d.setDate(d.getDate() + n)
  d.setHours(10, 0, 0, 0)
  return d.toISOString()
}

